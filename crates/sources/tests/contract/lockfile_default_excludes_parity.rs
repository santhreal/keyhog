//! WHY: Lockfile exclusion parity and precision contract (Row 17, Row 88):
//! Every major ecosystem lockfile registered in `rules/default_excludes.toml` must
//! be excluded by default during scans so that hash-rich lockfile trees do not flood
//! output with false positives, while remaining fully scannable when default excludes
//! are explicitly disabled. This test derives the lockfile variant space dynamically
//! from `rules/default_excludes.toml` at runtime and verifies detection precision over
//! realistic hash-rich fixture bytes with planted secrets in both directions.
//!
//! WHAT IT DOES NOT CATCH:
//! Custom proprietary in-house lockfile formats that are not registered in the Tier-B
//! `rules/default_excludes.toml` configuration table.

use keyhog_core::Source;
use keyhog_sources::FilesystemSource;
use std::collections::BTreeSet;
use std::path::Path;
use toml::Value;

fn repo_root() -> &'static Path {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("crates/")
        .parent()
        .expect("repo root")
}

fn load_default_exclude_filenames() -> BTreeSet<String> {
    let root = repo_root();
    let excludes_path = root.join("rules/default_excludes.toml");
    assert!(
        excludes_path.exists(),
        "rules/default_excludes.toml must exist"
    );

    let content =
        std::fs::read_to_string(&excludes_path).expect("read rules/default_excludes.toml");
    let parsed: Value = toml::from_str(&content).expect("parse rules/default_excludes.toml");

    let filenames_array = parsed
        .get("default_excludes")
        .and_then(|t| t.get("filenames"))
        .and_then(|v| v.as_array())
        .expect("default_excludes.filenames array must exist");

    filenames_array
        .iter()
        .filter_map(|v| v.as_str().map(|s| s.to_string()))
        .collect()
}

