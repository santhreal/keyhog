#[test]
fn default_excludes_rule_table_is_bidirectionally_verified_over_fixture_bytes() {
    let filenames = load_default_exclude_filenames();
    assert!(
        !filenames.is_empty(),
        "default_excludes.filenames must contain entries"
    );

    for filename in &filenames {
        let temp_dir = tempfile::tempdir().expect("create temp dir for lockfile fixture");
        let root = temp_dir.path();

        let source_secret = format!(
            "ghp_plantedsource_{}_0123456789ABCDEF012345",
            filename.replace('.', "_")
        );
        let lockfile_secret = format!(
            "ghp_plantedlockfile_{}_0123456789ABCDEF012345",
            filename.replace('.', "_")
        );

        let src_dir = root.join("src");
        std::fs::create_dir_all(&src_dir).expect("create src dir");
        let source_file_path = src_dir.join("index.js");
        std::fs::write(
            &source_file_path,
            format!("// Real source file\nconst API_KEY = \"{source_secret}\";\n"),
        )
        .expect("write source file");

        let lockfile_path = root.join(filename);
        let lockfile_content = generate_hash_rich_lockfile_content(filename, &lockfile_secret);
        std::fs::write(&lockfile_path, lockfile_content).expect("write lockfile fixture");

        // Direction 1: Default excludes ENABLED (`respect_default_excludes: true`)
        // - Lockfile must be completely excluded from emitted chunks
        // - The source file secret must be emitted with its path
        {
            let source = FilesystemSource::new(root.to_path_buf()).with_default_excludes(true);
            let chunks: Vec<keyhog_core::Chunk> = source.chunks().filter_map(Result::ok).collect();

            let has_source_secret = chunks.iter().any(|c| c.data.contains(&source_secret));
            let has_lockfile_secret = chunks.iter().any(|c| c.data.contains(&lockfile_secret));

            assert!(
                has_source_secret,
                "Default excludes enabled: source secret in 'src/index.js' must be discovered for fixture '{filename}'"
            );
            assert!(
                !has_lockfile_secret,
                "Default excludes enabled: lockfile secret in '{filename}' must be EXCLUDED and not emitted"
            );

            for chunk in &chunks {
                if let Some(path) = &chunk.metadata.path {
                    assert!(
                        !path.ends_with(filename),
                        "Default excludes enabled: chunk path '{path}' must not match excluded lockfile '{filename}'"
                    );
                }
            }
        }

        // Direction 2: Default excludes DISABLED (`respect_default_excludes: false`)
        // - Lockfile must be SCANNED and emitted in chunks
        // - Both the source file secret and the lockfile secret must be emitted with their respective paths
        {
            let source = FilesystemSource::new(root.to_path_buf()).with_default_excludes(false);
            let chunks: Vec<keyhog_core::Chunk> = source.chunks().filter_map(Result::ok).collect();

            let has_source_secret = chunks.iter().any(|c| c.data.contains(&source_secret));
            let has_lockfile_secret = chunks.iter().any(|c| c.data.contains(&lockfile_secret));

            assert!(
                has_source_secret,
                "Default excludes disabled: source secret in 'src/index.js' must be discovered for fixture '{filename}'"
            );
            assert!(
                has_lockfile_secret,
                "Default excludes disabled: lockfile secret in '{filename}' must be DISCOVERED when default excludes are disabled"
            );

            let lockfile_chunk_emitted = chunks.iter().any(|c| {
                c.metadata
                    .path
                    .as_deref()
                    .map(|p| p.ends_with(filename))
                    .unwrap_or(false)
            });
            assert!(
                lockfile_chunk_emitted,
                "Default excludes disabled: a chunk with path ending in '{filename}' must be emitted"
            );
        }
    }
}

#[test]
fn default_excludes_case_insensitivity_parity() {
    let filenames = load_default_exclude_filenames();

    // Verify case-insensitive exclusion behavior on sample variants (e.g. Cargo.lock vs cargo.lock)
    for filename in &filenames {
        let temp_dir = tempfile::tempdir().expect("create temp dir");
        let root = temp_dir.path();

        let uppercase_variant = if filename.contains('-') {
            filename
                .split('-')
                .map(|part| {
                    let mut c = part.chars();
                    match c.next() {
                        None => String::new(),
                        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
                    }
                })
                .collect::<Vec<_>>()
                .join("-")
        } else {
            let mut c = filename.chars();
            match c.next() {
                None => String::new(),
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
            }
        };

        let lockfile_secret = format!(
            "ghp_variant_{}_0123456789ABCDEF012345",
            filename.replace('.', "_")
        );
        let lockfile_path = root.join(&uppercase_variant);
        let lockfile_content = generate_hash_rich_lockfile_content(filename, &lockfile_secret);
        std::fs::write(&lockfile_path, lockfile_content).expect("write lockfile variant");

        // Direction 1: Excluded
        {
            let source = FilesystemSource::new(root.to_path_buf()).with_default_excludes(true);
            let chunks: Vec<keyhog_core::Chunk> = source.chunks().filter_map(Result::ok).collect();
            let has_lockfile_secret = chunks.iter().any(|c| c.data.contains(&lockfile_secret));
            assert!(
                !has_lockfile_secret,
                "Case variant '{uppercase_variant}' must be excluded by default_excludes (case-insensitive)"
            );
        }

        // Direction 2: Included when default excludes disabled
        {
            let source = FilesystemSource::new(root.to_path_buf()).with_default_excludes(false);
            let chunks: Vec<keyhog_core::Chunk> = source.chunks().filter_map(Result::ok).collect();
            let has_lockfile_secret = chunks.iter().any(|c| c.data.contains(&lockfile_secret));
            assert!(
                has_lockfile_secret,
                "Case variant '{uppercase_variant}' must be included when default excludes disabled"
            );
        }
    }
}
