//! Static metric descriptors and registry table for `MetricId`.

use serde::{Deserialize, Serialize};

use super::MetricId;

/// Measurement behavior associated with a metric.
#[derive(Serialize, Deserialize, Clone, Copy, Debug, Eq, PartialEq)]
pub enum MetricKind {
    Counter,
    Duration,
    Gauge,
    Distribution,
}

/// Stable unit associated with a metric value.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum MetricUnit {
    Bytes,
    Count,
    Milliseconds,
    Nanoseconds,
}

/// Static metric metadata. Every string is embedded in the binary.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct MetricDescriptor {
    pub id: MetricId,
    pub name: &'static str,
    pub kind: MetricKind,
    pub unit: MetricUnit,
}

const fn metric(
    id: MetricId,
    name: &'static str,
    kind: MetricKind,
    unit: MetricUnit,
) -> MetricDescriptor {
    MetricDescriptor {
        id,
        name,
        kind,
        unit,
    }
}

