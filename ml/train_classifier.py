def _write_weights(
    blob: bytes,
    args,
    metrics,
    real_metrics=None,
    calibration_artifact=None,
) -> None:
    """Write the serialized weights: `--write` overwrites the crate's
    `weights.bin` (backing up the old one to `.bak`); otherwise a scratch file
    next to the corpus, never touching the shipped crate."""
    if args.features == rust_features.NUM_FEATURES:
        quantized_blob = serialize_quantized(blob, args.features)
        feature_schema_digest = rust_features.quantized_schema_digest()
    else:
        if args.write:
            raise SystemExit(
                "REFUSING to write: shipped quantized serving requires the current "
                f"{rust_features.NUM_FEATURES}-feature model"
            )
        quantized_blob = None
        feature_schema_digest = None
    if calibration_artifact is None:
        calibration_artifact = build_pattern_calibration_artifact(
            f"moe-v1-{weights_fnv1a64(blob)}",
            None,
            [],
            [],
            [],
            [],
        )
    if calibration_artifact.get("model_version") != (
        f"moe-v1-{weights_fnv1a64(blob)}"
    ):
        raise ValueError("pattern calibration model version does not match weights")
    pattern_calibration_model_card_summary(calibration_artifact)
    if args.write:
        real = real_metrics or {}
        recall = real.get("recall_at_0_40_floor", real.get("real_pos_recall_at_0.40_floor"))
        if not isinstance(recall, (float, int)):
            raise SystemExit(
                "REFUSING to write: real held-out metrics must include numeric "
                "recall_at_0_40_floor before weights.bin is touched"
            )
        if not isinstance(real.get("per_class"), dict):
            raise SystemExit(
                "REFUSING to write: real held-out metrics must include per_class "
                "precision/recall before weights.bin is touched"
            )
        if not isinstance(real.get("per_detector"), dict):
            raise SystemExit(
                "REFUSING to write: real held-out metrics must include per_detector "
                "precision/recall before weights.bin is touched"
            )
        if not isinstance(real.get("per_recall_sensitive_class"), dict):
            raise SystemExit(
                "REFUSING to write: real held-out metrics must include "
                "per_recall_sensitive_class precision/recall before weights.bin is touched"
            )
        if os.path.exists(args.out):
            shutil.copy2(args.out, args.out + ".bak")
            sys.stderr.write(f"backed up existing weights -> {args.out}.bak\n")
        with open(args.out, "wb") as fh:
            fh.write(blob)
        sys.stderr.write(f"wrote {args.out}\n")
        if quantized_blob is not None:
            if os.path.exists(args.quantized_out):
                shutil.copy2(args.quantized_out, args.quantized_out + ".bak")
                sys.stderr.write(
                    f"backed up existing quantized model -> {args.quantized_out}.bak\n"
                )
            with open(args.quantized_out, "wb") as fh:
                fh.write(quantized_blob)
            sys.stderr.write(f"wrote {args.quantized_out}\n")
        if os.path.exists(args.pattern_calibration_out):
            shutil.copy2(
                args.pattern_calibration_out,
                args.pattern_calibration_out + ".bak",
            )
            sys.stderr.write(
                "backed up existing pattern calibration -> "
                f"{args.pattern_calibration_out}.bak\n"
            )
        with open(args.pattern_calibration_out, "wb") as fh:
            fh.write(serialize_pattern_calibration_artifact(calibration_artifact))
        sys.stderr.write(f"wrote {args.pattern_calibration_out}\n")
    else:
        # default: write next to corpus for inspection, do NOT touch the crate
        scratch = os.path.join(os.path.dirname(args.corpus) or ".", f"weights_{args.features}.bin")
        with open(scratch, "wb") as fh:
            fh.write(blob)
        sys.stderr.write(f"wrote {scratch} (pass --write to update {args.out})\n")
        if quantized_blob is not None:
            quantized_scratch = os.path.join(
                os.path.dirname(args.corpus) or "",
                f"quantized_moe_{args.features}.bin",
            )
            with open(quantized_scratch, "wb") as fh:
                fh.write(quantized_blob)
            sys.stderr.write(
                f"wrote {quantized_scratch} (pass --write to update {args.quantized_out})\n"
            )
        calibration_scratch = os.path.join(
            os.path.dirname(args.corpus) or "",
            f"pattern_calibration_{args.features}.json",
        )
        with open(calibration_scratch, "wb") as fh:
            fh.write(serialize_pattern_calibration_artifact(calibration_artifact))
        sys.stderr.write(
            f"wrote {calibration_scratch} "
            f"(pass --write to update {args.pattern_calibration_out})\n"
        )
    write_model_card(
        blob,
        quantized_blob,
        feature_schema_digest,
        args,
        metrics,
        real_metrics,
        calibration_artifact,
    )


def _class_floor(metric: dict) -> float | None:
    value = metric.get("recall_at_0_40_floor")
    if isinstance(value, (float, int)):
        return float(value)
    return None


def _load_baseline_group(path: str, group: str) -> dict:
    try:
        with open(path, encoding="utf-8") as fh:
            card = json.load(fh)
    except (OSError, json.JSONDecodeError):
        return {}
    if not isinstance(card, dict):
        return {}
    metrics = (
        card.get("metrics", {})
        .get("real_heldout", {})
        .get(group, {})
    )
    return metrics if isinstance(metrics, dict) else {}


def _load_baseline_per_class(path: str) -> dict:
    return _load_baseline_group(path, "per_recall_sensitive_class")


def _load_baseline_per_detector(path: str) -> dict:
    return _load_baseline_group(path, "per_detector")


def _repo_path(path: str) -> pathlib.Path:
    candidate = pathlib.Path(path)
    return candidate if candidate.is_absolute() else REPO_ROOT / candidate


def _bench_report_module():
    bench_dir = str(REPO_ROOT / "benchmarks")
    if bench_dir not in sys.path:
        sys.path.insert(0, bench_dir)
    from bench import report as bench_report

    return bench_report


def six_scanner_differential_comparison(real_metrics: dict, args) -> dict:
    """Compare every positive held-out class to the benchmark differential."""
    per_class = real_metrics.get("per_class")
    if not isinstance(per_class, dict):
        raise ValueError(
            "real held-out metrics must include per_class before the "
            "six-scanner differential can be attached"
        )

    bench_report = _bench_report_module()
    results_dir = _repo_path(args.differential_results)
    results = bench_report.load_results(results_dir)
    if not results:
        raise ValueError(
            f"no benchmark RunResult JSON files found under {results_dir}; "
            "run the differential benchmark before retraining"
        )
    differential = bench_report.class_recall_differential(
        results,
        args.differential_corpus,
        bench_report.FULL_DIFFERENTIAL_SCANNERS,
    )
    rows = differential.get("rows") or {}

    missing = []
    classes = {}
    for kind, metric in sorted(per_class.items()):
        if not isinstance(metric, dict):
            continue
        n_pos = int(metric.get("n_pos") or 0)
        if n_pos <= 0:
            continue
        row = rows.get(kind)
        if row is None:
            missing.append(kind)
            continue
        best = row["best_competitor"]
        classes[kind] = {
            "heldout_n_pos": n_pos,
            "heldout_recall_at_0_40_floor": _class_floor(metric),
            "benchmark_keyhog": row["keyhog"],
            "benchmark_best_competitor": {
                "scanner": best["scanner"],
                "recall": best["recall"],
                "precision": best["precision"],
                "f1": best["f1"],
                "tp": best["tp"],
                "fn": best["fn"],
            },
            "benchmark_recall_gap": row["recall_gap"],
            "benchmark_competitors": row["competitors"],
        }

    if missing:
        raise ValueError(
            "six-scanner differential is missing positive held-out class(es) "
            f"for `{args.differential_corpus}`: {', '.join(missing)}"
        )
    if not classes:
        raise ValueError(
            "real held-out per_class metrics contain no positive-bearing class "
            "to compare against the six-scanner differential"
        )

    return {
        "corpus": differential["corpus"],
        "results_dir": str(results_dir),
        "required_scanners": list(bench_report.FULL_DIFFERENTIAL_SCANNERS),
        "scanners": differential["scanners"],
        "scanner_count": differential["scanner_count"],
        "benchmark_category_count": differential["category_count"],
        "compared_class_count": len(classes),
        "classes": classes,
    }


def per_class_gate_error(real_metrics: dict, args) -> str:
    """Guard classes whose detector policy lets the model reduce recall."""
    per_class = real_metrics.get("per_recall_sensitive_class")
    if not isinstance(per_class, dict):
        return (
            "REFUSING to write: real held-out metrics must include "
            "per_recall_sensitive_class precision/recall so aggregate recall "
            "cannot hide failures on model-authoritative paths\n"
        )

    offenders = []
    for kind, metric in sorted(per_class.items()):
        if not isinstance(metric, dict):
            continue
        n_pos = int(metric.get("n_pos") or 0)
        if n_pos < args.min_real_class_support:
            continue
        recall = _class_floor(metric)
        if recall is None or recall < args.min_real_class_recall:
            shown = "missing" if recall is None else f"{recall:.4f}"
            offenders.append(
                f"{kind} recall@0.40={shown} < floor {args.min_real_class_recall:.4f} "
                f"(n_pos={n_pos})"
            )

    regressions = []
    baseline = _load_baseline_per_class(args.baseline_model_card) if args.write else {}
    for kind, old_metric in sorted(baseline.items()):
        if kind not in per_class or not isinstance(old_metric, dict):
            continue
        new_metric = per_class.get(kind)
        if not isinstance(new_metric, dict):
            continue
        if int(new_metric.get("n_pos") or 0) < args.min_real_class_support:
            continue
        old_recall = _class_floor(old_metric)
        new_recall = _class_floor(new_metric)
        if old_recall is None or new_recall is None:
            continue
        drop = old_recall - new_recall
        if drop > args.max_real_class_recall_drop + 1e-12:
            regressions.append(
                f"{kind} recall@0.40 dropped {old_recall:.4f}->{new_recall:.4f} "
                f"(allowed {args.max_real_class_recall_drop:.4f})"
            )

    if not offenders and not regressions:
        return ""
    lines = ["REFUSING to write: per-class real held-out recall gate failed"]
    lines.extend(f"  - {item}" for item in offenders)
    lines.extend(f"  - {item}" for item in regressions)
    lines.append("")
    return "\n".join(lines)


def per_detector_gate_error(real_metrics: dict, args) -> str:
    """Return a refusal message when detector-level real recall is unsafe.

    Class gates cannot expose one broken detector hidden inside a broad class,
    so detector metrics are independently load-bearing.
    """
    per_detector = real_metrics.get("per_detector")
    if not isinstance(per_detector, dict):
        return (
            "REFUSING to write: real held-out metrics must include per_detector "
            "precision/recall so aggregate and class recall cannot hide detector failures\n"
        )

    offenders = []
    recall_sensitive = detector_policy.recall_sensitive_finding_ids()
    for detector_id in sorted(recall_sensitive):
        metric = per_detector.get(detector_id)
        if not isinstance(metric, dict):
            offenders.append(f"{detector_id} has no real held-out candidates")
            continue
        n_pos = int(metric.get("n_pos") or 0)
        if n_pos < args.min_real_detector_support:
            offenders.append(
                f"{detector_id} has {n_pos} positive held-out candidate(s), requires "
                f"{args.min_real_detector_support}"
            )
            continue
        n_neg = int(metric.get("n_neg") or 0)
        if n_neg < args.min_real_detector_negative_support:
            offenders.append(
                f"{detector_id} has {n_neg} negative held-out candidate(s), requires "
                f"{args.min_real_detector_negative_support}"
            )
            continue
        recall = _class_floor(metric)
        if recall is None or recall < args.min_real_detector_recall:
            shown = "missing" if recall is None else f"{recall:.4f}"
            offenders.append(
                f"{detector_id} recall@0.40={shown} < floor "
                f"{args.min_real_detector_recall:.4f} (n_pos={n_pos})"
            )

    regressions = []
    baseline = _load_baseline_per_detector(args.baseline_model_card) if args.write else {}
    for detector_id, old_metric in sorted(baseline.items()):
        if not detector_policy.model_can_reduce_recall(detector_id):
            continue
        new_metric = per_detector.get(detector_id)
        if not isinstance(old_metric, dict) or not isinstance(new_metric, dict):
            continue
        if int(new_metric.get("n_pos") or 0) < args.min_real_detector_support:
            continue
        old_recall = _class_floor(old_metric)
        new_recall = _class_floor(new_metric)
        if old_recall is None or new_recall is None:
            continue
        drop = old_recall - new_recall
        if drop > args.max_real_detector_recall_drop + 1e-12:
            regressions.append(
                f"{detector_id} recall@0.40 dropped {old_recall:.4f}->{new_recall:.4f} "
                f"(allowed {args.max_real_detector_recall_drop:.4f})"
            )

    if not offenders and not regressions:
        return ""
    lines = ["REFUSING to write: per-detector real held-out recall gate failed"]
    lines.extend(f"  - {item}" for item in offenders)
    lines.extend(f"  - {item}" for item in regressions)
    lines.append("")
    return "\n".join(lines)


