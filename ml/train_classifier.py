def pattern_calibration_model_card_summary(artifact):
    if artifact.get("schema_version") != PATTERN_CALIBRATION_SCHEMA_VERSION:
        raise ValueError("model-card calibration summary requires the current schema")
    if artifact.get("identity_schema") != PATTERN_CALIBRATION_IDENTITY_SCHEMA:
        raise ValueError("model-card calibration summary has a stale identity schema")
    if not valid_model_version(artifact.get("model_version")):
        raise ValueError("model-card calibration summary has an invalid model version")
    floors = artifact.get("floors")
    if not isinstance(floors, dict):
        raise ValueError("model-card calibration summary requires floors")
    validate_calibration_floors(floors)
    entries = artifact.get("entries")
    if not isinstance(entries, list):
        raise ValueError("model-card calibration summary requires entries")
    detector_digest = artifact.get("detector_digest")
    if entries:
        if (
            not isinstance(detector_digest, str)
            or len(detector_digest) != 16
            or any(ch not in "0123456789abcdef" for ch in detector_digest)
        ):
            raise ValueError(
                "populated model-card calibration summary requires detector digest"
            )
    elif detector_digest is not None:
        raise ValueError(
            "empty model-card calibration summary requires null detector digest"
        )
    positive_support = 0
    negative_support = 0
    eligible_entries = 0
    recalls = []
    blocking_recalls = []
    brier_scores = []
    eces = []
    expected_entry_fields = {
        "detector_id",
        "pattern_index",
        "candidate_channel",
        "source_role",
        "context_class",
        "metrics",
    }
    expected_metric_fields = {
        "f1",
        "precision",
        "recall",
        "recall_at_blocking_floor",
        "brier_score",
        "ece",
        "positive_support",
        "negative_support",
    }
    for entry in entries:
        if not isinstance(entry, dict) or set(entry) != expected_entry_fields:
            raise ValueError("model-card calibration entry has an invalid shape")
        if (
            not valid_detector_slug(entry["detector_id"])
            or isinstance(entry["pattern_index"], bool)
            or not isinstance(entry["pattern_index"], int)
            or not 0 <= entry["pattern_index"] <= 0xFFFFFFFF
            or entry["candidate_channel"] != "pattern"
            or entry["source_role"] not in PATTERN_CALIBRATION_SOURCE_ROLES
            or entry["context_class"] not in PATTERN_CALIBRATION_CONTEXT_CLASSES
        ):
            raise ValueError("model-card calibration entry has an invalid identity")
        metrics = entry["metrics"]
        if not isinstance(metrics, dict) or set(metrics) != expected_metric_fields:
            raise ValueError("model-card calibration entry has invalid metrics")
        for support_field in ("positive_support", "negative_support"):
            support = metrics[support_field]
            if isinstance(support, bool) or not isinstance(support, int) or support < 0:
                raise ValueError("model-card calibration support must be nonnegative integers")
        for metric_field in expected_metric_fields - {
            "positive_support",
            "negative_support",
        }:
            value = metrics[metric_field]
            if (
                isinstance(value, bool)
                or not isinstance(value, (int, float))
                or not math.isfinite(value)
                or not 0.0 <= value <= 1.0
            ):
                raise ValueError(
                    "model-card calibration quality metrics must be probabilities"
                )
        positive_support += int(metrics["positive_support"])
        negative_support += int(metrics["negative_support"])
        recalls.append(float(metrics["recall"]))
        blocking_recalls.append(float(metrics["recall_at_blocking_floor"]))
        brier_scores.append(float(metrics["brier_score"]))
        eces.append(float(metrics["ece"]))
        eligible_entries += int(
            metrics["positive_support"] >= floors["minimum_positive_support"]
            and metrics["negative_support"] >= floors["minimum_negative_support"]
            and metrics["recall"] >= floors["minimum_recall"]
            and metrics["recall_at_blocking_floor"] >= floors["minimum_recall"]
            and metrics["brier_score"] <= floors["maximum_brier_score"]
            and metrics["ece"] <= floors["maximum_ece"]
        )
    return {
        "artifact_sha256": hashlib.sha256(
            serialize_pattern_calibration_artifact(artifact)
        ).hexdigest(),
        "schema_version": artifact["schema_version"],
        "identity_schema": artifact["identity_schema"],
        "model_version": artifact["model_version"],
        "detector_digest": artifact.get("detector_digest"),
        "status": "abstaining" if not entries else "calibrated",
        "floors": dict(floors),
        "entry_count": len(entries),
        "eligible_entry_count": eligible_entries,
        "aggregate_metrics": {
            "positive_support": positive_support,
            "negative_support": negative_support,
            "minimum_recall": min(recalls) if recalls else None,
            "minimum_recall_at_blocking_floor": (
                min(blocking_recalls) if blocking_recalls else None
            ),
            "maximum_brier_score": max(brier_scores) if brier_scores else None,
            "maximum_ece": max(eces) if eces else None,
        },
    }


def validation_selection_key(
    probs,
    labels,
    groups=None,
    real_mask=None,
    minimum_real_metrics=None,
):
    """Choose checkpoints by the same recall constraints shipping enforces.

    Groups are derived only from detector policy plus the real validation split;
    the held-out test split remains untouched. Fewer recall-sensitive classes
    below the report floor wins first, then the worst class recall, then
    aggregate F1. Synthetic-only training retains aggregate-F1 selection.
    """
    f1, _, _ = prf(probs, labels, 0.5)
    if groups is None:
        return (f1,)
    recalls = []
    normalized = np.asarray([group or "" for group in groups], dtype=object)
    labels = np.asarray(labels)
    probs = np.asarray(probs)
    for group in sorted(set(normalized) - {""}):
        positive = (normalized == group) & (labels >= 0.5)
        if int(positive.sum()) < 2:
            continue
        recalls.append(float(np.mean(probs[positive] >= REAL_RECALL_FLOOR)))
    failing = sum(recall < RECALL_SENSITIVE_CLASS_FLOOR for recall in recalls)
    minimum = min(recalls, default=1.0)
    if real_mask is None or not np.asarray(real_mask, dtype=bool).any():
        return (-failing, minimum, f1)
    real_mask = np.asarray(real_mask, dtype=bool)
    real_f1, real_precision, _ = prf(probs[real_mask], labels[real_mask], 0.5)
    minimum_real_f1, minimum_real_precision = (
        minimum_real_metrics
        if minimum_real_metrics is not None
        else (REAL_F1_FLOOR, REAL_PRECISION_FLOOR)
    )
    eligible = int(
        real_f1 >= minimum_real_f1 and real_precision >= minimum_real_precision
    )
    return (eligible, -failing, minimum, real_f1, real_precision, f1)


def real_eval(probs, labels, classes, detectors=None, thr=0.5):
    """Held-out real-distribution metrics. The headline is recall on real
    positives clearing the 0.40 report floor, the number the synthetic-only
    model failed (it scored real ambiguous secrets ~0.02)."""
    f1, prec, rec = prf(probs, labels, thr)
    pos = [float(probs[i]) for i, l in enumerate(labels) if l >= 0.5]
    neg = [float(probs[i]) for i, l in enumerate(labels) if l < 0.5]
    floor_recall = (
        float(np.mean([1.0 if p >= REAL_RECALL_FLOOR else 0.0 for p in pos]))
        if pos
        else float("nan")
    )
    out = {
        "real_f1": round(f1, 4),
        "real_precision": round(prec, 4),
        "real_recall": round(rec, 4),
        "n_test": int(len(labels)),
        "n_pos": len(pos),
        "n_neg": len(neg),
        "pos_mean_score": round(float(np.mean(pos)), 4) if pos else None,
        "neg_mean_score": round(float(np.mean(neg)), 4) if neg else None,
        "real_pos_recall_at_0.40_floor": round(floor_recall, 4),
        "per_class": per_class_eval(probs, labels, classes, thr, REAL_RECALL_FLOOR),
    }
    if detectors is not None:
        out["per_detector"] = per_class_eval(
            probs,
            labels,
            detectors,
            thr,
            REAL_RECALL_FLOOR,
        )
        sensitive = np.asarray(
            [detector_policy.model_can_reduce_recall(detector) for detector in detectors],
            dtype=bool,
        )
        out["per_recall_sensitive_class"] = per_class_eval(
            probs[sensitive],
            labels[sensitive],
            [kind for kind, keep in zip(classes, sensitive) if keep],
            thr,
            REAL_RECALL_FLOOR,
        )
    return out


def real_metric_summary(metrics: dict) -> dict:
    """Compact terminal summary; the model card retains the complete tables."""
    headline = {
        key: metrics.get(key)
        for key in (
            "real_f1",
            "real_precision",
            "real_recall",
            "real_pos_recall_at_0.40_floor",
            "n_test",
            "n_pos",
            "n_neg",
        )
    }
    per_detector = metrics.get("per_detector", {})
    headline["recall_sensitive_detectors"] = {
        detector_id: metric.get("recall_at_0_40_floor")
        for detector_id, metric in sorted(per_detector.items())
        if isinstance(metric, dict)
        and int(metric.get("n_pos") or 0) > 0
        and detector_policy.model_can_reduce_recall(detector_id)
    }
    headline["zero_recall_detectors"] = [
        detector_id
        for detector_id, metric in sorted(per_detector.items())
        if isinstance(metric, dict)
        and int(metric.get("n_pos") or 0) > 0
        and metric.get("recall_at_0_40_floor") == 0.0
    ]
    return headline


def train_blended(
    Xs,
    ys,
    kinds_s,
    detectors_s,
    Xr,
    yr,
    classes_r,
    detectors_r,
    files_r,
    num_features,
    epochs,
    seed,
    max_detector_positive_multiplier,
    max_recall_sensitive_class_multiplier,
    initial_weights_path=None,
    learning_rate=2e-3,
):
    """Train on synthetic (breadth) + real-TRAIN, select on synthetic-val +
    real-val, and report on a real-TEST held out by file (no leakage). Returns
    (model, synthetic_val_metrics, real_heldout_metrics)."""
    import torch

    rng = np.random.default_rng(seed)
    si = rng.permutation(len(ys))
    ssplit = int(len(ys) * 0.85)
    s_tr, s_va = si[:ssplit], si[ssplit:]
    r_tr, r_va, r_te = _group_split(files_r, seed)

    X = np.concatenate([Xs, Xr])
    y = np.concatenate([ys, yr])
    off = len(ys)
    tr = np.concatenate([s_tr, r_tr + off])
    va = np.concatenate([s_va, r_va + off])  # model selection (syn + real val)

    sample_weights = detector_balanced_sample_weights(
        y,
        tr,
        [*detectors_s, *detectors_r],
        max_detector_positive_multiplier,
    )
    sample_weights *= recall_sensitive_class_sample_weights(
        len(y),
        off,
        yr,
        classes_r,
        detectors_r,
        r_tr,
        max_recall_sensitive_class_multiplier,
    )

    validation_groups = np.asarray(
        [""] * len(ys)
        + [
            (kind or "unknown")
            if detector_policy.model_can_reduce_recall(detector)
            else ""
            for kind, detector in zip(classes_r, detectors_r)
        ],
        dtype=object,
    )
    validation_real_mask = np.asarray(
        [False] * len(ys) + [True] * len(yr),
        dtype=bool,
    )

    model = _fit(
        X,
        y,
        tr,
        va,
        num_features,
        epochs,
        seed,
        sample_weights,
        validation_groups,
        validation_real_mask,
        initial_weights_path,
        learning_rate,
    )
    with torch.no_grad():
        syn_val_p = model(torch.from_numpy(Xs[s_va])).numpy()
        real_te_p = model(torch.from_numpy(Xr[r_te])).numpy() if len(r_te) else np.array([])
    syn_metrics = report(syn_val_p, ys[s_va], [kinds_s[i] for i in s_va])
    real_metrics = (
        real_eval(
            real_te_p,
            yr[r_te],
            [classes_r[i] for i in r_te],
            [detectors_r[i] for i in r_te],
        )
        if len(r_te)
        else {"note": "no real test split"}
    )
    return model, syn_metrics, real_metrics


def detector_balanced_sample_weights(
    combined_labels,
    combined_train_indices,
    combined_detectors,
    max_multiplier,
):
    """Balance positive loss inside each detector without held-out data.

    Global class weighting cannot protect a detector whose own candidate stream
    is much more negative-heavy than the aggregate. This multiplier brings each
    positive-bearing detector toward its own train-split class balance and
    positive support, capped so a tiny family cannot dominate the model.
    """
    if not math.isfinite(max_multiplier) or max_multiplier < 1.0:
        raise ValueError("max detector positive multiplier must be finite and >= 1.0")
    labels = np.asarray(combined_labels)
    train_labels = labels[combined_train_indices]
    global_positive_weight = float((train_labels == 0).sum()) / max(
        1.0, float((train_labels == 1).sum())
    )
    if len(combined_detectors) != len(labels):
        raise ValueError("combined detector identities must match combined labels")
    counts: dict[str, list[int]] = {}
    for index in combined_train_indices:
        detector = combined_detectors[index]
        if not detector_policy.model_can_reduce_recall(detector):
            continue
        pair = counts.setdefault(detector, [0, 0])
        pair[1 if labels[index] > 0.5 else 0] += 1

    weights = np.ones(len(labels), dtype=np.float32)
    positive_support_target = max((pair[1] for pair in counts.values()), default=1)
    for index in combined_train_indices:
        if labels[index] <= 0.5:
            continue
        detector = combined_detectors[index]
        if detector not in counts:
            continue
        negatives, positives = counts[detector]
        if positives == 0:
            continue
        detector_positive_weight = negatives / positives if negatives else 0.0
        balance_multiplier = max(1.0, detector_positive_weight / global_positive_weight)
        support_multiplier = positive_support_target / positives
        weights[index] = min(
            max_multiplier,
            max(balance_multiplier, support_multiplier),
        )
    return weights


def recall_sensitive_class_sample_weights(
    combined_length,
    real_offset,
    real_labels,
    real_classes,
    real_detectors,
    real_train_indices,
    max_multiplier,
):
    """Balance positive recall-sensitive classes using train rows only."""
    if not math.isfinite(max_multiplier) or max_multiplier < 1.0:
        raise ValueError(
            "max recall-sensitive class multiplier must be finite and >= 1.0"
        )
    counts: dict[tuple[str, str], int] = {}
    for index in real_train_indices:
        detector = real_detectors[index]
        if real_labels[index] <= 0.5 or not detector_policy.model_can_reduce_recall(detector):
            continue
        key = (detector, real_classes[index] or "unknown")
        counts[key] = counts.get(key, 0) + 1

    target = max(counts.values(), default=1)
    weights = np.ones(combined_length, dtype=np.float32)
    for index in real_train_indices:
        detector = real_detectors[index]
        if real_labels[index] <= 0.5 or not detector_policy.model_can_reduce_recall(detector):
            continue
        count = counts[(detector, real_classes[index] or "unknown")]
        weights[real_offset + index] = min(max_multiplier, target / count)
    return weights


def prf(probs, labels, thr):
    pred = (probs >= thr).astype(np.float32)
    tp = float(((pred == 1) & (labels == 1)).sum())
    fp = float(((pred == 1) & (labels == 0)).sum())
    fn = float(((pred == 0) & (labels == 1)).sum())
    prec = tp / (tp + fp) if tp + fp else 0.0
    rec = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * prec * rec / (prec + rec) if prec + rec else 0.0
    return f1, prec, rec


def report(probs, labels, kinds):
    f1, prec, rec = prf(probs, labels, 0.5)
    # base64-binary FP behaviour: mean score on those negatives (want it LOW)
    bin_scores = [probs[i] for i, k in enumerate(kinds) if k == "base64-binary"]
    bin_mean = float(np.mean(bin_scores)) if bin_scores else float("nan")
    bin_flagged = (
        float(np.mean([1.0 if s >= 0.5 else 0.0 for s in bin_scores]))
        if bin_scores
        else float("nan")
    )
    return {
        "f1": f1,
        "precision": prec,
        "recall": rec,
        "n_val": int(len(labels)),
        "base64_binary_mean_score": bin_mean,
        "base64_binary_flag_rate": bin_flagged,
        "n_base64_binary_val": len(bin_scores),
    }


