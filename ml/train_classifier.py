def probe_gate_error(probes: dict, threshold: float = 0.5) -> str:
    """Reject a model that reverses a canonical positive/negative contract."""
    failures = []
    for name, result in probes.items():
        score = result.get("score")
        want = result.get("want")
        if not isinstance(score, (float, int)) or want not in {"high", "low"}:
            failures.append(f"{name}: malformed probe result {result!r}")
        elif want == "high" and score < threshold:
            failures.append(f"{name}: score {score:.3f} < {threshold:.3f}")
        elif want == "low" and score >= threshold:
            failures.append(f"{name}: score {score:.3f} >= {threshold:.3f}")
    if not failures:
        return ""
    return "REFUSING model: canonical probe contract failed: " + "; ".join(failures) + "\n"


def parameter_count(num_features: int) -> int:
    return (
        num_features * EXPERT_COUNT
        + EXPERT_COUNT
        + EXPERT_COUNT
        * (num_features * FC1 + FC1 + FC1 * FC2 + FC2 + FC2 + 1)
    )


def serialize(model, num_features: int) -> bytes:
    """Flatten the model into the exact little-endian f32 layout ml_weights.rs
    parses. Linear.weight is [out, in] row-major, which is precisely the
    `weights[out_idx*in + in_idx]` indexing the Rust forward pass uses."""
    sd = model.state_dict()
    buf = []

    def add(t):
        buf.append(np.asarray(t.detach().cpu().numpy(), dtype="<f4").ravel())

    add(sd["gate.weight"])  # [6, D]
    add(sd["gate.bias"])  # [6]
    for e in range(EXPERT_COUNT):
        add(sd[f"experts.{e}.fc1.weight"])  # [32, D]
        add(sd[f"experts.{e}.fc1.bias"])  # [32]
        add(sd[f"experts.{e}.fc2.weight"])  # [16, 32]
        add(sd[f"experts.{e}.fc2.bias"])  # [16]
        add(sd[f"experts.{e}.fc3.weight"])  # [1, 16]
        add(sd[f"experts.{e}.fc3.bias"])  # [1]

    flat = np.concatenate(buf)
    expected = parameter_count(num_features)
    assert flat.size == expected, f"layout size {flat.size} != expected {expected}"
    return flat.tobytes()

def serialize_quantized(blob: bytes, num_features: int) -> bytes:
    """Serialize the current model into the canonical signed Q7 wire format."""
    if num_features != rust_features.NUM_FEATURES:
        raise ValueError(
            "quantized serving requires the current "
            f"{rust_features.NUM_FEATURES}-feature schema, got {num_features}"
        )
    expected_bytes = parameter_count(num_features) * np.dtype("<f4").itemsize
    if len(blob) != expected_bytes:
        raise ValueError(
            f"quantized serving expected {expected_bytes} model bytes, got {len(blob)}"
        )
    flat = np.frombuffer(blob, dtype="<f4")
    if not np.isfinite(flat).all():
        raise ValueError("quantized serving cannot encode non-finite model parameters")
    scale = 1 << QUANTIZED_FRACTIONAL_BITS
    scaled = flat.astype(np.float64) * scale
    rounded = np.where(
        scaled >= 0.0,
        np.floor(scaled + 0.5),
        np.ceil(scaled - 0.5),
    )
    quantized = np.clip(rounded, -32768, 32767).astype("<i2")
    parameter_bound = int(np.max(np.abs(quantized.astype(np.int64))))
    dense_terms = max(num_features, FC1, FC2)
    maximum_dense_accumulator = (
        dense_terms * 32768 * parameter_bound
        + scale * parameter_bound
        + scale // 2
    )
    if maximum_dense_accumulator > np.iinfo(np.int32).max:
        raise ValueError(
            "quantized serving parameter magnitude "
            f"{parameter_bound} exceeds the VYRE i32 arithmetic bound"
        )
    payload = quantized.tobytes()
    payload_digest = hashlib.sha256(payload).digest()
    header = struct.pack(
        "<8s6HBBHI32s",
        b"KHQMOE\0\1",
        QUANTIZED_MODEL_FORMAT_VERSION,
        QUANTIZED_FEATURE_SCHEMA_VERSION,
        num_features,
        EXPERT_COUNT,
        FC1,
        FC2,
        QUANTIZED_FRACTIONAL_BITS,
        QUANTIZED_ROUNDING_TIES_AWAY,
        0,
        len(payload),
        payload_digest,
    )
    return header + payload


def weights_fnv1a64(blob: bytes) -> str:
    h = 0xCBF29CE484222325
    for b in blob:
        h ^= b
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return f"{h:016x}"


def file_sha256(path: str | None) -> str | None:
    if not path:
        return None
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_model_card(
    blob: bytes,
    quantized_blob: bytes | None,
    feature_schema_digest: str | None,
    args,
    metrics,
    real_metrics=None,
    calibration_artifact=None,
) -> None:
    """Write model-card provenance beside the serialized weights.

    Shipped writes require real held-out metrics. A synthetic-only card would be
    stale the moment the binary is used on real corpora, so `--write` refuses
    that path before touching `weights.bin`.
    """
    if args.write and not real_metrics:
        raise SystemExit(
            "REFUSING to write: --write now requires --real-corpus so the shipped "
            "model_card.json carries leakage-free real held-out recall"
        )

    digest = weights_fnv1a64(blob)
    if calibration_artifact is None:
        calibration_artifact = build_pattern_calibration_artifact(
            f"moe-v1-{digest}", None, [], [], [], []
        )
    if calibration_artifact.get("model_version") != f"moe-v1-{digest}":
        raise ValueError("pattern calibration model version does not match weights")
    calibration_card = pattern_calibration_model_card_summary(calibration_artifact)
    real_card = dict(real_metrics) if real_metrics else {
        "note": "scratch training only; shipped writes require --real-corpus"
    }
    if "real_pos_recall_at_0.40_floor" in real_card:
        real_card["recall_at_0_40_floor"] = real_card["real_pos_recall_at_0.40_floor"]
    if args.write and not isinstance(real_card.get("recall_at_0_40_floor"), (float, int)):
        raise SystemExit(
            "REFUSING to write: real held-out metrics must include numeric "
            "recall_at_0_40_floor for model_card.json"
        )
    if args.write and not isinstance(real_card.get("per_class"), dict):
        raise SystemExit(
            "REFUSING to write: real held-out metrics must include per_class "
            "precision/recall for model_card.json"
        )
    if args.write and not isinstance(real_card.get("per_detector"), dict):
        raise SystemExit(
            "REFUSING to write: real held-out metrics must include per_detector "
            "precision/recall for model_card.json"
        )
    if args.write and not isinstance(real_card.get("per_recall_sensitive_class"), dict):
        raise SystemExit(
            "REFUSING to write: real held-out metrics must include "
            "per_recall_sensitive_class precision/recall for model_card.json"
        )
    if getattr(args, "real_corpus", None) and not isinstance(
        real_card.get("six_scanner_differential"),
        dict,
    ):
        raise SystemExit(
            "REFUSING retrain artifact: real-corpus model cards must include the "
            "full six-scanner per-class differential comparison"
        )
    card = {
        "schema_version": 3
        if isinstance(real_card.get("six_scanner_differential"), dict)
        else (2 if args.write else 1),
        "model_version": f"moe-v1-{digest}",
        "weights_fnv1a64": digest,
        "architecture": "moe-v1",
        "feature_count": args.features,
        "recorded_date": datetime.date.today().isoformat(),
        "trainer": "ml/train_classifier.py",
        "feature_source": "Rust dump_features serve path",
        "pattern_calibration": calibration_card,
        "training_inputs": {
            "synthetic": args.corpus,
            "synthetic_sha256": file_sha256(args.corpus),
            "real_distribution": args.real_corpus
            if args.real_corpus
            else "scratch training only; not shipped",
            "real_distribution_sha256": file_sha256(args.real_corpus),
        },
        "training_parameters": {
            "epochs": args.epochs,
            "seed": args.seed,
            "max_detector_positive_multiplier": args.max_detector_positive_multiplier,
            "max_recall_sensitive_class_multiplier": args.max_recall_sensitive_class_multiplier,
            "initial_weights": args.init_weights,
            "initial_weights_sha256": file_sha256(args.init_weights),
            "learning_rate": args.learning_rate,
        },
        "metrics": {
            "synthetic_heldout": metrics,
            "real_heldout": real_card,
        },
    }
    if quantized_blob is not None:
        if feature_schema_digest is None:
            raise ValueError("quantized model card requires a feature-schema digest")
        card["quantized_serving"] = {
            "artifact_sha256": hashlib.sha256(quantized_blob).hexdigest(),
            "feature_schema_sha256": feature_schema_digest,
            "feature_schema_version": QUANTIZED_FEATURE_SCHEMA_VERSION,
            "format_version": QUANTIZED_MODEL_FORMAT_VERSION,
            "fractional_bits": QUANTIZED_FRACTIONAL_BITS,
            "rounding": "nearest-ties-away-from-zero",
        }

    if args.write:
        path = args.model_card
        if os.path.exists(path):
            shutil.copy2(path, path + ".bak")
            sys.stderr.write(f"backed up existing model card -> {path}.bak\n")
    else:
        stem = os.path.splitext(os.path.basename(args.out))[0] or f"weights_{args.features}"
        path = os.path.join(os.path.dirname(args.corpus) or ".", f"{stem}.model_card.json")

    with open(path, "w", encoding="utf-8") as fh:
        json.dump(card, fh, indent=2, sort_keys=True)
        fh.write("\n")
    sys.stderr.write(f"wrote {path}\n")


